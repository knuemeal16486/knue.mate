  /// 정류장 이름으로 인덱스 찾기
  static int? getStopIndex(
    String routeNumber,
    String direction,
    String stopName,
  ) {
    final stops = routeStops[routeNumber]?[direction];
    if (stops == null) return null;
    final index = stops.indexOf(stopName);
    return index >= 0 ? index : null;
  }

  /// 다음 정류장 이름 가져오기
  static String? getNextStop(
    String routeNumber,
    String direction,
    String currentStop,
  ) {
    final stops = routeStops[routeNumber]?[direction];
    if (stops == null) return null;
    final index = stops.indexOf(currentStop);
    if (index < 0 || index >= stops.length - 1) return null;
    return stops[index + 1];
  }
