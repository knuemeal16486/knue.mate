/// 화면 맨 위에서 고르는 주제. 선언 순서가 화면 순서다.
enum LegalTopic {
  housing('집 계약할 때', '계약 전부터 나갈 때까지, 순서대로 모았어요.'),
  tutoring('학원강사(과외)', '시작하기 전에 알아 두면 든든한 것들이에요.'),
  partTime('아르바이트', '일한 만큼 제대로 받는 방법이에요.'),
  life('대학 생활', '살다 보면 한 번쯤 마주치는 일들이에요.');

  final String label;

  /// 주제를 고르면 목록 위에 나오는 한 줄 소개.
  final String intro;
  const LegalTopic(this.label, this.intro);
}

class LegalTip {
  final String id;

  /// 이 항목이 나오는 주제. 세금처럼 과외와 알바에 똑같이 해당하는 건
  /// 두 주제에 모두 넣는다.
  final List<LegalTopic> topics;

  /// 주제 안의 묶음 제목("계약 전", "일하는 동안" …). 목록에 처음 나오는
  /// 순서대로 화면에 놓인다.
  final String group;
  final String title;

  /// 목록 카드에서 제목 아래에 보이는 한 줄.
  final String summary;
  final List<String> points;

  /// 근거 조문. 학생이 직접 찾아볼 수 있게 법 이름과 조 번호로 적는다.
  /// 법 조문이 아니라 요령인 항목은 비워 둔다.
  final String? basis;
  final String? linkLabel;
  final String? linkUrl;

  const LegalTip({
    required this.id,
    required this.topics,
    required this.group,
    required this.title,
    required this.summary,
    required this.points,
    this.basis,
    this.linkLabel,
    this.linkUrl,
  });
}

