/// 본문 한 줄을 굵게 칠할 조각과 아닌 조각으로 나눈 것.
class LegalSpan {
  final String text;
  final bool bold;
  const LegalSpan(this.text, {this.bold = false});
}

/// `**굵게**` 표시를 조각으로 푼다. 짝이 안 맞는 `**`는 그 뒤를 보통 글씨로
/// 둔다(글이 통째로 굵어지는 것보다 표시가 빠진 쪽이 덜 거슬린다).
List<LegalSpan> parseLegalEmphasis(String text) {
  final parts = text.split('**');
  final balanced = parts.length.isOdd;
  final out = <LegalSpan>[];
  for (var i = 0; i < parts.length; i++) {
    if (parts[i].isEmpty) continue;
    out.add(LegalSpan(parts[i], bold: balanced && i.isOdd));
  }
  return out;
}

/// 굵게 표시를 걷어낸 글. 검색과 복사에 쓴다.
String plainLegalText(String text) => text.replaceAll('**', '');

/// 폭 없는 이음 문자. 이 문자 앞뒤로는 줄이 바뀌지 않는다.
const String _joiner = '‍';

/// 한글이 낱말 중간에서 줄바꿈되지 않게 한다("받/아 두세요" → "받아/두세요").
///
/// Flutter는 한글을 글자마다 끊을 수 있다고 봐서, 줄 끝에 한 글자만 남기고
/// 낱말을 쪼갠다. 낱말 안의 글자 사이마다 이음 문자를 끼워 띄어쓰기에서만
/// 줄이 바뀌게 한다. 화면에 그릴 때만 쓰고, 검색·복사에는 원문을 쓴다.
String keepKoreanWords(String text) => text.replaceAllMapped(
      RegExp(r'(\S)(?=\S)'),
      (m) => '${m[1]}$_joiner',
    );

/// 화면에 그릴 조각. [parseLegalEmphasis]에 낱말 붙이기를 더한 것으로,
/// 굵은 조각과 보통 조각이 띄어쓰기 없이 맞닿은 곳("**갑구**: …")도 붙인다.
List<LegalSpan> legalDisplaySpans(String text) {
  final spans = parseLegalEmphasis(text);
  bool isSpace(String s) => s.trim().isEmpty;
  return [
    for (var i = 0; i < spans.length; i++)
      LegalSpan(
        keepKoreanWords(spans[i].text) +
            (i + 1 < spans.length &&
                    !isSpace(spans[i].text[spans[i].text.length - 1]) &&
                    !isSpace(spans[i + 1].text[0])
                ? _joiner
                : ''),
        bold: spans[i].bold,
      ),
  ];
}

/// 본문 한 줄을 화면에서 어떻게 그릴지.
enum LegalPointKind {
  /// 보통 줄.
  normal,

  /// "예) …" 계산 예시.
  example,

  /// 따옴표로 통째로 감싼, 그대로 옮겨 쓸 문구(특약 등).
  quote,
}

LegalPointKind legalPointKind(String point) {
  final p = plainLegalText(point).trim();
  if (p.startsWith('예)')) return LegalPointKind.example;
  if (p.length > 2 && p.startsWith('"') && p.endsWith('"')) {
    return LegalPointKind.quote;
  }
  return LegalPointKind.normal;
}

/// 주제·묶음·검색어로 추린다. null인 조건은 걸지 않는다.
/// 검색어는 제목·요약·본문·근거 조문 어디에 걸려도 잡힌다.
List<LegalTip> filterLegalTips(
  List<LegalTip> tips, {
  LegalTopic? topic,
  String? group,
  String query = '',
}) {
  final q = query.trim().toLowerCase();
  return tips.where((t) {
    if (topic != null && !t.topics.contains(topic)) return false;
    if (group != null && t.group != group) return false;
    if (q.isEmpty) return true;
    return t.title.toLowerCase().contains(q) ||
        t.summary.toLowerCase().contains(q) ||
        (t.basis?.toLowerCase().contains(q) ?? false) ||
        t.points.any((p) => plainLegalText(p).toLowerCase().contains(q));
  }).toList();
}

/// 묶음 제목별로 나눈다. 묶음도, 묶음 안의 항목도 [tips]에 나온 순서 그대로다.
Map<String, List<LegalTip>> groupLegalTips(List<LegalTip> tips) {
  final out = <String, List<LegalTip>>{};
  for (final t in tips) {
    out.putIfAbsent(t.group, () => []).add(t);
  }
  return out;
}

/// 검색어가 주제마다 몇 건 걸리는지. 걸리는 것이 없는 주제는 빠진다.
/// 지금 주제에 결과가 없을 때 "다른 주제에 있다"고 알려 주는 데 쓴다.
Map<LegalTopic, int> countLegalMatchesByTopic(
  List<LegalTip> tips,
  String query,
) {
  final out = <LegalTopic, int>{};
  if (query.trim().isEmpty) return out;
  for (final topic in LegalTopic.values) {
    final n = filterLegalTips(tips, topic: topic, query: query).length;
    if (n > 0) out[topic] = n;
  }
  return out;
}
